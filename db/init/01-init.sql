-- ให้เวลาที่ฐานข้อมูลคืนมาเป็นเวลาไทย
-- ต้องห่อด้วย DO เพราะ ALTER DATABASE ต้องการ "ชื่อ" ไม่ใช่ฟังก์ชัน
do $$
begin
  execute format('alter database %I set timezone to %L', current_database(), 'Asia/Bangkok');
end
$$;
